-- Supplier profile management: company details, contacts, addresses and bank accounts.
-- Oracle DDL is idempotent so this script can safely be rerun.

BEGIN
    EXECUTE IMMEDIATE '
        CREATE TABLE supplier_profiles (
            supplier_id NUMBER(19) NOT NULL,
            legal_name VARCHAR2(200),
            registration_number VARCHAR2(80),
            vat_number VARCHAR2(50),
            website VARCHAR2(255),
            preferred_language VARCHAR2(12) DEFAULT ''de'' NOT NULL,
            preferred_currency CHAR(3) DEFAULT ''EUR'' NOT NULL,
            payment_terms_days NUMBER(3) DEFAULT 30 NOT NULL,
            created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
            updated_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
            CONSTRAINT pk_supplier_profiles PRIMARY KEY (supplier_id),
            CONSTRAINT fk_supplier_profiles_supplier FOREIGN KEY (supplier_id)
                REFERENCES suppliers(id) ON DELETE CASCADE,
            CONSTRAINT chk_supplier_profile_payment_terms CHECK (payment_terms_days BETWEEN 0 AND 365),
            CONSTRAINT chk_supplier_profile_currency CHECK (REGEXP_LIKE(preferred_currency, ''^[A-Z]{3}$'')),
            CONSTRAINT chk_supplier_profile_language CHECK (REGEXP_LIKE(preferred_language, ''^[a-zA-Z]{2,3}(-[a-zA-Z0-9]{2,8})*$''))
        )';
EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

BEGIN
    EXECUTE IMMEDIATE '
        CREATE TABLE supplier_contacts (
            id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            supplier_id NUMBER(19) NOT NULL,
            contact_type VARCHAR2(30) DEFAULT ''GENERAL'' NOT NULL,
            first_name VARCHAR2(100) NOT NULL,
            last_name VARCHAR2(100) NOT NULL,
            job_title VARCHAR2(120),
            email VARCHAR2(150),
            phone VARCHAR2(30),
            is_primary CHAR(1) DEFAULT ''N'' NOT NULL,
            created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
            updated_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
            CONSTRAINT fk_supplier_contacts_supplier FOREIGN KEY (supplier_id) REFERENCES suppliers(id) ON DELETE CASCADE,
            CONSTRAINT chk_supplier_contact_primary CHECK (is_primary IN (''Y'', ''N''))
        )';
EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

BEGIN
    EXECUTE IMMEDIATE '
        CREATE TABLE supplier_addresses (
            id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            supplier_id NUMBER(19) NOT NULL,
            address_type VARCHAR2(20) NOT NULL,
            label VARCHAR2(100),
            company_name VARCHAR2(200),
            street VARCHAR2(180) NOT NULL,
            street2 VARCHAR2(180),
            postal_code VARCHAR2(20) NOT NULL,
            city VARCHAR2(100) NOT NULL,
            region VARCHAR2(100),
            country CHAR(2) NOT NULL,
            is_default CHAR(1) DEFAULT ''N'' NOT NULL,
            created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
            updated_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
            CONSTRAINT fk_supplier_addresses_supplier FOREIGN KEY (supplier_id) REFERENCES suppliers(id) ON DELETE CASCADE,
            CONSTRAINT chk_supplier_address_type CHECK (address_type IN (''REGISTERED'', ''BILLING'', ''SHIPPING'', ''OTHER'')),
            CONSTRAINT chk_supplier_address_default CHECK (is_default IN (''Y'', ''N'')),
            CONSTRAINT chk_supplier_address_country CHECK (REGEXP_LIKE(country, ''^[A-Z]{2}$''))
        )';
EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

BEGIN
    EXECUTE IMMEDIATE '
        CREATE TABLE supplier_bank_accounts (
            id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            supplier_id NUMBER(19) NOT NULL,
            account_holder_encrypted VARCHAR2(512) NOT NULL,
            iban_encrypted VARCHAR2(512) NOT NULL,
            bic VARCHAR2(11),
            bank_name VARCHAR2(150),
            currency CHAR(3) DEFAULT ''EUR'' NOT NULL,
            encryption_key_version VARCHAR2(30) NOT NULL,
            is_primary CHAR(1) DEFAULT ''N'' NOT NULL,
            created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
            updated_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
            CONSTRAINT fk_supplier_bank_accounts_supplier FOREIGN KEY (supplier_id) REFERENCES suppliers(id) ON DELETE CASCADE,
            CONSTRAINT chk_supplier_bank_primary CHECK (is_primary IN (''Y'', ''N'')),
            CONSTRAINT chk_supplier_bank_currency CHECK (REGEXP_LIKE(currency, ''^[A-Z]{3}$''))
        )';
EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

