-- Supplier document management and compliance metadata.
-- Binary objects are stored outside Oracle in a private object store.
-- Oracle stores metadata and lifecycle state only.
WHENEVER SQLERROR EXIT SQL.SQLCODE

BEGIN
    EXECUTE IMMEDIATE 'CREATE TABLE supplier_document_types (
        id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        code VARCHAR2(60) NOT NULL,
        name VARCHAR2(150) NOT NULL,
        description VARCHAR2(500),
        allowed_mime_types CLOB NOT NULL,
        max_file_size_bytes NUMBER(19) DEFAULT 10485760 NOT NULL,
        is_active NUMBER(1) DEFAULT 1 NOT NULL,
        created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
        updated_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
        CONSTRAINT uq_supplier_document_type_code UNIQUE (code),
        CONSTRAINT chk_supplier_document_type_mimes CHECK (allowed_mime_types IS JSON),
        CONSTRAINT chk_supplier_document_type_size CHECK (max_file_size_bytes BETWEEN 1 AND 104857600),
        CONSTRAINT chk_supplier_document_type_active CHECK (is_active IN (0,1))
    )';
EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

BEGIN
    EXECUTE IMMEDIATE 'CREATE TABLE supplier_document_requirements (
        id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        document_type_id NUMBER(19) NOT NULL,
        supplier_category_id NUMBER(19),
        country_code CHAR(2),
        scope_key VARCHAR2(80) NOT NULL,
        is_required NUMBER(1) DEFAULT 1 NOT NULL,
        validity_days NUMBER(10),
        warning_days NUMBER(10) DEFAULT 30 NOT NULL,
        is_active NUMBER(1) DEFAULT 1 NOT NULL,
        created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
        updated_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
        CONSTRAINT fk_supplier_doc_req_type FOREIGN KEY (document_type_id) REFERENCES supplier_document_types(id),
        CONSTRAINT fk_supplier_doc_req_category FOREIGN KEY (supplier_category_id) REFERENCES supplier_categories(id),
        CONSTRAINT uq_supplier_doc_req_scope UNIQUE (document_type_id, scope_key),
        CONSTRAINT chk_supplier_doc_req_required CHECK (is_required IN (0,1)),
        CONSTRAINT chk_supplier_doc_req_validity CHECK (validity_days IS NULL OR validity_days > 0),
        CONSTRAINT chk_supplier_doc_req_warning CHECK (warning_days BETWEEN 0 AND 3650),
        CONSTRAINT chk_supplier_doc_req_active CHECK (is_active IN (0,1))
    )';
EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

BEGIN
    EXECUTE IMMEDIATE 'CREATE TABLE supplier_documents (
        id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        supplier_id NUMBER(10) NOT NULL,
        document_type_id NUMBER(19) NOT NULL,
        title VARCHAR2(200) NOT NULL,
        current_version_id NUMBER(19),
        created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
        updated_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
        CONSTRAINT fk_supplier_document_supplier FOREIGN KEY (supplier_id) REFERENCES suppliers(id),
        CONSTRAINT fk_supplier_document_type FOREIGN KEY (document_type_id) REFERENCES supplier_document_types(id)
    )';
EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

BEGIN
    EXECUTE IMMEDIATE 'CREATE TABLE supplier_document_versions (
        id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        document_id NUMBER(19) NOT NULL,
        version_number NUMBER(10) NOT NULL,
        object_key VARCHAR2(512) NOT NULL,
        original_filename VARCHAR2(255) NOT NULL,
        detected_mime_type VARCHAR2(150) NOT NULL,
        file_size_bytes NUMBER(19) NOT NULL,
        checksum_sha256 CHAR(64) NOT NULL,
        scan_status VARCHAR2(20) DEFAULT ''PENDING'' NOT NULL,
        review_status VARCHAR2(20) DEFAULT ''PENDING'' NOT NULL,
        expires_at DATE,
        uploaded_by VARCHAR2(255) NOT NULL,
        uploaded_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
        reviewed_by VARCHAR2(255),
        reviewed_at TIMESTAMP,
        review_note VARCHAR2(1000),
        deleted_at TIMESTAMP,
        CONSTRAINT fk_supplier_doc_version_doc FOREIGN KEY (document_id) REFERENCES supplier_documents(id),
        CONSTRAINT uq_supplier_doc_version UNIQUE (document_id, version_number),
        CONSTRAINT uq_supplier_doc_object_key UNIQUE (object_key),
        CONSTRAINT chk_supplier_doc_version_number CHECK (version_number > 0),
        CONSTRAINT chk_supplier_doc_version_size CHECK (file_size_bytes BETWEEN 1 AND 104857600),
        CONSTRAINT chk_supplier_doc_scan_status CHECK (scan_status IN (''PENDING'', ''CLEAN'', ''INFECTED'', ''ERROR'')),
        CONSTRAINT chk_supplier_doc_review_status CHECK (review_status IN (''PENDING'', ''APPROVED'', ''REJECTED'')),
        CONSTRAINT chk_supplier_doc_checksum CHECK (REGEXP_LIKE(checksum_sha256, ''^[A-Fa-f0-9]{64}$''))
    )';
EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

BEGIN
    EXECUTE IMMEDIATE 'CREATE INDEX idx_supplier_doc_supplier_type ON supplier_documents (supplier_id, document_type_id, updated_at)';
EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

BEGIN
    EXECUTE IMMEDIATE 'CREATE INDEX idx_supplier_doc_expiry ON supplier_document_versions (expires_at, scan_status, review_status)';
EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

BEGIN
    EXECUTE IMMEDIATE 'CREATE INDEX idx_supplier_doc_review ON supplier_document_versions (review_status, scan_status, uploaded_at)';
EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

COMMENT ON TABLE supplier_documents IS 'Logical supplier compliance documents; file bytes live in private object storage';
COMMENT ON TABLE supplier_document_versions IS 'Immutable metadata for each uploaded document version; never stores file bytes';
COMMENT ON TABLE supplier_document_requirements IS 'Configurable supplier document requirements scoped by category and/or country';

