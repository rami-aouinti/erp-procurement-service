-- Supplier onboarding state machine.
-- Existing suppliers are backfilled as APPROVED to preserve current purchasing
-- behavior. New onboarding records must be created through the dedicated API.
WHENEVER SQLERROR EXIT SQL.SQLCODE

BEGIN
    EXECUTE IMMEDIATE '
        CREATE TABLE supplier_onboarding (
            supplier_id NUMBER(10) PRIMARY KEY,
            onboarding_status VARCHAR2(30) DEFAULT ''APPROVED'' NOT NULL,
            submitted_at TIMESTAMP,
            decided_at TIMESTAMP,
            decided_by VARCHAR2(255),
            previous_supplier_status VARCHAR2(20),
            decision_reason VARCHAR2(1000),
            version NUMBER(10) DEFAULT 1 NOT NULL,
            created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
            updated_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
            CONSTRAINT chk_supplier_onboarding_status CHECK (
                onboarding_status IN (''DRAFT'', ''PENDING_APPROVAL'', ''APPROVED'', ''REJECTED'', ''CHANGES_REQUESTED'')
            ),
            CONSTRAINT chk_supplier_onboarding_version CHECK (version > 0)
        )';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

BEGIN
    EXECUTE IMMEDIATE '
        CREATE TABLE supplier_onboarding_history (
            id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            supplier_id NUMBER(10) NOT NULL,
            from_status VARCHAR2(30),
            to_status VARCHAR2(30) NOT NULL,
            actor_id VARCHAR2(255) NOT NULL,
            actor_name VARCHAR2(255) NOT NULL,
            reason VARCHAR2(1000),
            request_id VARCHAR2(128),
            occurred_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
            CONSTRAINT fk_supplier_onboarding_history FOREIGN KEY (supplier_id)
                REFERENCES supplier_onboarding(supplier_id)
        )';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

BEGIN
    EXECUTE IMMEDIATE 'CREATE INDEX idx_supplier_onboarding_status ON supplier_onboarding (onboarding_status, updated_at)';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

INSERT INTO supplier_onboarding (supplier_id, onboarding_status)
SELECT s.id, 'APPROVED'
FROM suppliers s
WHERE NOT EXISTS (
    SELECT 1 FROM supplier_onboarding o WHERE o.supplier_id = s.id
);

