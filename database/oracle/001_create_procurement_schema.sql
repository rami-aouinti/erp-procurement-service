-- Initial Procurement & Inventory ERP schema
-- Target: Oracle Database Free 23c / FREEPDB1
-- Run as the application schema user (ERP_APP):
--   sqlplus ERP_APP/<password>@//localhost:1521/FREEPDB1
--   @database/oracle/001_create_procurement_schema.sql

WHENEVER SQLERROR EXIT SQL.SQLCODE

CREATE TABLE suppliers (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR2(150) NOT NULL,
    email VARCHAR2(150),
    phone VARCHAR2(30),
    tax_number VARCHAR2(50),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_suppliers PRIMARY KEY (id),
    CONSTRAINT uq_suppliers_email UNIQUE (email)
);

CREATE TABLE products (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    sku VARCHAR2(50) NOT NULL,
    name VARCHAR2(150) NOT NULL,
    description VARCHAR2(500),
    unit_price NUMBER(12, 2) NOT NULL,
    active NUMBER(1) DEFAULT 1 NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_products PRIMARY KEY (id),
    CONSTRAINT uq_products_sku UNIQUE (sku),
    CONSTRAINT chk_products_price CHECK (unit_price >= 0),
    CONSTRAINT chk_products_active CHECK (active IN (0, 1))
);

CREATE TABLE purchase_orders (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    order_number VARCHAR2(50) NOT NULL,
    supplier_id NUMBER NOT NULL,
    status VARCHAR2(30) DEFAULT 'DRAFT' NOT NULL,
    order_date DATE DEFAULT SYSDATE NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_purchase_orders PRIMARY KEY (id),
    CONSTRAINT uq_purchase_orders_number UNIQUE (order_number),
    CONSTRAINT fk_po_supplier FOREIGN KEY (supplier_id)
        REFERENCES suppliers (id),
    CONSTRAINT chk_po_status CHECK (
        status IN ('DRAFT', 'SUBMITTED', 'PARTIALLY_RECEIVED', 'RECEIVED', 'CANCELLED')
    )
);

CREATE TABLE purchase_order_lines (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    purchase_order_id NUMBER NOT NULL,
    product_id NUMBER NOT NULL,
    quantity NUMBER(12, 2) NOT NULL,
    unit_price NUMBER(12, 2) NOT NULL,
    CONSTRAINT pk_purchase_order_lines PRIMARY KEY (id),
    CONSTRAINT fk_pol_order FOREIGN KEY (purchase_order_id)
        REFERENCES purchase_orders (id),
    CONSTRAINT fk_pol_product FOREIGN KEY (product_id)
        REFERENCES products (id),
    CONSTRAINT chk_pol_quantity CHECK (quantity > 0),
    CONSTRAINT chk_pol_price CHECK (unit_price >= 0),
    CONSTRAINT uq_pol_order_product UNIQUE (purchase_order_id, product_id)
);

-- Index foreign-key columns used by joins and parent-row operations.
CREATE INDEX idx_po_supplier_id ON purchase_orders (supplier_id);
CREATE INDEX idx_pol_product_id ON purchase_order_lines (product_id);

COMMENT ON TABLE suppliers IS 'Companies that supply products to the organization';
COMMENT ON TABLE products IS 'ERP product catalogue';
COMMENT ON TABLE purchase_orders IS 'Purchase orders sent to suppliers';
COMMENT ON TABLE purchase_order_lines IS 'Products and quantities belonging to a purchase order';

PROMPT Procurement schema created successfully.
