-- Append-only Supplier audit trail.
-- No foreign key to suppliers: history must survive a supplier hard delete.
-- Only field names and safe metadata are stored; never store field values,
-- encrypted bank payloads, plaintext IBANs, secrets or document contents.

WHENEVER SQLERROR EXIT SQL.SQLCODE

BEGIN
    EXECUTE IMMEDIATE '
        CREATE TABLE supplier_audit_logs (
            id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            supplier_id NUMBER(10),
            entity_type VARCHAR2(40) NOT NULL,
            entity_id NUMBER(19),
            action VARCHAR2(30) NOT NULL,
            actor_type VARCHAR2(20) NOT NULL,
            actor_identifier VARCHAR2(255),
            actor_label VARCHAR2(160) NOT NULL,
            request_id VARCHAR2(128),
            changed_fields CLOB NOT NULL,
            occurred_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
            CONSTRAINT chk_supplier_audit_actor CHECK (actor_type IN (''USER'', ''SYSTEM'', ''ANONYMOUS'')),
            CONSTRAINT chk_supplier_audit_action CHECK (action IN (''CREATED'', ''UPDATED'', ''DELETED'', ''SECURITY_ROTATED'')),
            CONSTRAINT chk_supplier_audit_fields_json CHECK (changed_fields IS JSON)
        )';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

BEGIN
    EXECUTE IMMEDIATE '
        CREATE INDEX idx_supplier_audit_supplier_time
        ON supplier_audit_logs (supplier_id, occurred_at)';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

BEGIN
    EXECUTE IMMEDIATE '
        CREATE INDEX idx_supplier_audit_entity
        ON supplier_audit_logs (entity_type, entity_id, occurred_at)';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

COMMENT ON TABLE supplier_audit_logs IS
    'Append-only history of Supplier business changes; deliberately independent from supplier deletion';

