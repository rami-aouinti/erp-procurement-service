CREATE TABLE goods_receipts (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    receipt_number VARCHAR2(30) NOT NULL UNIQUE,
    purchase_order_id NUMBER NOT NULL,
    received_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT fk_gr_purchase_order
        FOREIGN KEY (purchase_order_id) REFERENCES purchase_orders(id)
);

CREATE TABLE goods_receipt_lines (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    goods_receipt_id NUMBER NOT NULL,
    purchase_order_line_id NUMBER NOT NULL,
    quantity NUMBER(12, 2) NOT NULL,
    CONSTRAINT fk_grl_receipt
        FOREIGN KEY (goods_receipt_id) REFERENCES goods_receipts(id),
    CONSTRAINT fk_grl_order_line
        FOREIGN KEY (purchase_order_line_id) REFERENCES purchase_order_lines(id),
    CONSTRAINT chk_grl_quantity CHECK (quantity > 0)
);

CREATE TABLE inventory (
    product_id NUMBER PRIMARY KEY,
    quantity_on_hand NUMBER(12, 2) DEFAULT 0 NOT NULL,
    updated_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT fk_inventory_product
        FOREIGN KEY (product_id) REFERENCES products(id),
    CONSTRAINT chk_inventory_quantity CHECK (quantity_on_hand >= 0)
);

CREATE TABLE inventory_movements (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id NUMBER NOT NULL,
    goods_receipt_line_id NUMBER NOT NULL,
    movement_type VARCHAR2(20) NOT NULL,
    quantity NUMBER(12, 2) NOT NULL,
    movement_date TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT fk_im_product
        FOREIGN KEY (product_id) REFERENCES products(id),
    CONSTRAINT fk_im_receipt_line
        FOREIGN KEY (goods_receipt_line_id) REFERENCES goods_receipt_lines(id),
    CONSTRAINT chk_im_type CHECK (movement_type IN ('IN', 'OUT', 'ADJUSTMENT')),
    CONSTRAINT chk_im_quantity CHECK (quantity > 0),
    CONSTRAINT uq_im_receipt_line UNIQUE (goods_receipt_line_id)
);

CREATE INDEX idx_gr_purchase_order_id ON goods_receipts(purchase_order_id);
CREATE INDEX idx_grl_order_line_id ON goods_receipt_lines(purchase_order_line_id);
CREATE INDEX idx_im_product_date ON inventory_movements(product_id, movement_date);

COMMENT ON TABLE goods_receipts IS 'Goods receipt documents for purchase orders';
COMMENT ON TABLE goods_receipt_lines IS 'Products and quantities recorded in a goods receipt';
COMMENT ON TABLE inventory IS 'Current on-hand quantity per product';
COMMENT ON TABLE inventory_movements IS 'Audit trail of stock increases, decreases and adjustments';

PROMPT Creating atomic goods receiving procedure...

CREATE OR REPLACE PROCEDURE receive_purchase_order_line (
    p_order_number IN VARCHAR2,
    p_sku          IN VARCHAR2,
    p_quantity     IN NUMBER
) AS
    v_order_id          purchase_orders.id%TYPE;
    v_order_status      purchase_orders.status%TYPE;
    v_order_line_id     purchase_order_lines.id%TYPE;
    v_product_id        products.id%TYPE;
    v_ordered_quantity  purchase_order_lines.quantity%TYPE;
    v_received_quantity purchase_order_lines.received_quantity%TYPE;
    v_receipt_id        goods_receipts.id%TYPE;
    v_receipt_number    goods_receipts.receipt_number%TYPE;
    v_new_status        purchase_orders.status%TYPE;
    v_remaining_lines   NUMBER;
BEGIN
    IF p_quantity IS NULL OR p_quantity <= 0 THEN
        RAISE_APPLICATION_ERROR(-20001, 'Receipt quantity must be greater than zero.');
    END IF;

    -- Lock the order so two concurrent receipts cannot update it inconsistently.
    SELECT id, status
      INTO v_order_id, v_order_status
      FROM purchase_orders
     WHERE order_number = p_order_number
       FOR UPDATE;

    IF v_order_status NOT IN ('SUBMITTED', 'PARTIALLY_RECEIVED') THEN
        RAISE_APPLICATION_ERROR(-20002, 'Only submitted or partially received orders can receive goods.');
    END IF;

    -- Lock the selected order line before checking its remaining quantity.
    SELECT pol.id, pol.product_id, pol.quantity, pol.received_quantity
      INTO v_order_line_id, v_product_id, v_ordered_quantity, v_received_quantity
      FROM purchase_order_lines pol
      JOIN products p ON p.id = pol.product_id
     WHERE pol.purchase_order_id = v_order_id
       AND p.sku = p_sku
       FOR UPDATE OF pol.received_quantity;

    IF p_quantity > (v_ordered_quantity - v_received_quantity) THEN
        RAISE_APPLICATION_ERROR(-20003, 'Receipt quantity exceeds the remaining ordered quantity.');
    END IF;

    v_receipt_number := 'GR-' || TO_CHAR(SYSTIMESTAMP, 'YYYYMMDDHH24MISSFF3');

    INSERT INTO goods_receipts (receipt_number, purchase_order_id)
    VALUES (v_receipt_number, v_order_id)
    RETURNING id INTO v_receipt_id;

    INSERT INTO goods_receipt_lines (goods_receipt_id, purchase_order_line_id, quantity)
    VALUES (v_receipt_id, v_order_line_id, p_quantity);

    UPDATE purchase_order_lines
       SET received_quantity = received_quantity + p_quantity
     WHERE id = v_order_line_id;

    MERGE INTO inventory target
    USING (SELECT v_product_id AS product_id FROM dual) source
       ON (target.product_id = source.product_id)
     WHEN MATCHED THEN
        UPDATE SET
            target.quantity_on_hand = target.quantity_on_hand + p_quantity,
            target.updated_at = SYSTIMESTAMP
     WHEN NOT MATCHED THEN
        INSERT (product_id, quantity_on_hand, updated_at)
        VALUES (source.product_id, p_quantity, SYSTIMESTAMP);

    INSERT INTO inventory_movements (
        product_id, goods_receipt_line_id, movement_type, quantity
    ) VALUES (
        v_product_id, (SELECT id FROM goods_receipt_lines WHERE goods_receipt_id = v_receipt_id),
        'IN', p_quantity
    );

    SELECT COUNT(*)
      INTO v_remaining_lines
      FROM purchase_order_lines
     WHERE purchase_order_id = v_order_id
       AND received_quantity < quantity;

    IF v_remaining_lines = 0 THEN
        v_new_status := 'RECEIVED';
    ELSE
        v_new_status := 'PARTIALLY_RECEIVED';
    END IF;

    UPDATE purchase_orders
       SET status = v_new_status
     WHERE id = v_order_id;

    COMMIT;

    DBMS_OUTPUT.PUT_LINE(
        'Goods received: ' || p_quantity || ' x ' || p_sku ||
        ' for ' || p_order_number || '. Receipt: ' || v_receipt_number
    );
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        ROLLBACK;
        RAISE_APPLICATION_ERROR(-20004, 'Purchase order or product line was not found.');
    WHEN OTHERS THEN
        ROLLBACK;
        RAISE;
END;
/

SHOW ERRORS PROCEDURE receive_purchase_order_line;

