    EXECUTE IMMEDIATE 'CREATE TABLE supplier_categories (
        id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        parent_id NUMBER(19),
        code VARCHAR2(50) NOT NULL,
        name VARCHAR2(150) NOT NULL,
        description VARCHAR2(500),
        is_active NUMBER(1) DEFAULT 1 NOT NULL,
        created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
        updated_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
        CONSTRAINT uq_supplier_category_code UNIQUE (code),
        CONSTRAINT fk_supplier_category_parent FOREIGN KEY (parent_id) REFERENCES supplier_categories(id),
        CONSTRAINT chk_supplier_category_active CHECK (is_active IN (0,1)),
        CONSTRAINT chk_supplier_category_not_self CHECK (parent_id IS NULL OR parent_id <> id)
    )';
EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF;
END;
